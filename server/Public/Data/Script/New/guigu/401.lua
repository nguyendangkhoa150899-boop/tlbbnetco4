	--local CurTime = GetHourTime()		--Trß¾c m£t Th¶i gian 
	local CurTime = GetQuarterTime()		--Trß¾c m£t Th¶i gian 
	local CurDaytime = floor(CurTime/100)	--Trß¾c m£t Th¶i gian (Thiên)
	local CurQuarterTime = mod(CurTime,100) 	--Trß¾c m£t Th¶i gian (Mß¶i låm phút)
