		end
	end
	return 1
end

function x760401_ProduceItemParamData(sceneId, selfId, BagPos)
	local index = random(getn(x760401_g_scenePosInfoList))
	local sId = x760401_g_scenePosInfoList[index].sceneId
	local scene, sceneName, x, z, r = x760401_GetScenePosInfo(sceneId,sId)

	if nil == BagPos or BagPos <0 then
		local logstr ="chengxiongdatu::x760401_ProduceItemParamData.. BagPos=".. BagPos 
		MissionLog(sceneId, logstr)
		return
	end
	if scene == nil or sceneName == nil 
		or x == nil or z == nil or r == nil then
		local logstr ="chengxiongdatu::x760401_ProduceItemParamData.."
			.."scene=".. type(scene)..",sceneName=".. type(sceneName)
			.."x=".. type(x)..",z=".. type(z)..",r=".. type(r)
		
		MissionLog(sceneId, logstr)
		return
	end
	
	local LogInfo	= format("[ChengXiong]: x760401_ProduceItemParamData(sceneId=%d, GUID=%0X), Scene=%d, SceneName=%s, MissionX=%d, MissionZ=%d, MissionR=%d",
														sceneId,
														LuaFnObjId2Guid(sceneId, selfId),
														scene,
														sceneName,
														x,
														z,
														r)	
	MissionLog(sceneId, LogInfo)	
	
	SetBagItemParam(sceneId, selfId, BagPos, 0, 0, 1)
	SetBagItemParam(sceneId, selfId, BagPos, 1, 1, scene)
	SetBagItemParam(sceneId, selfId, BagPos, 3, 1, x)
	SetBagItemParam(sceneId, selfId, BagPos, 5, 1, z)
	SetBagItemParam(sceneId, selfId, BagPos, 7, 1, r)

end

