function x760401_GetScenePosInfo(sceneId,selectSceneId)

	local index = random(getn(x760401_g_scenePosInfoList))
	local subIndex = random(getn(x760401_g_scenePosInfoList[index].posList))
		
	local sceneId = x760401_g_scenePosInfoList[index].sceneId
	local sceneName = x760401_g_scenePosInfoList[index].sceneName
	local x			= x760401_g_scenePosInfoList[index].posList[subIndex].x
	local z 		= x760401_g_scenePosInfoList[index].posList[subIndex].z
	local r 		= x760401_g_scenePosInfoList[index].posList[subIndex].r
	
	if selectSceneId>=0 and selectSceneId ~= -1 then
		for i, v in x760401_g_scenePosInfoList do
			if v.sceneId == selectSceneId then
				local index = random(getn(v.posList))
