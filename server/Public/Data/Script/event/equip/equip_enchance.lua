	text = text.."此装备的"..x809262_g_EquipName[equipType].sanhai.."增加至"..x809262_g_qianghuaLevelT[arg0][1].."#H点。"
	end
	end
	end
	

	BeginEvent(sceneId)
	AddText(sceneId,text);
	EndEvent(sceneId)
	DispatchMissionTips(sceneId,selfId)
end

