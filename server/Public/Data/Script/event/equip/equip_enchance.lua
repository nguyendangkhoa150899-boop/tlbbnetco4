function x809262_DoFinishEnhance( sceneId, selfId, index )
	local itemidx1 = floor(index / 1000)
	local itemidx2 = mod(index , 1000)
	local text="装备强化成功！"
	local 	qianhuLevel = GetBagItemParam( sceneId, selfId, itemidx1, 3, 1)
	local suiqi = random(100)
	local ret,arg0 = -6,qianhuLevel
	if x809262_g_qianghuaLevelT[qianhuLevel] == nil then
	x809262_MsgBox( sceneId, selfId, "装备强化等级错误" )
	return
	end
        if  suiqi <= floor(x809262_g_qianghuaLevelT[qianhuLevel][3] + (GetBagItemParam( sceneId, selfId, itemidx1, 1, 1)/x809262_g_qianghuaLevelT[qianhuLevel][2])*100)  or GetBagItemParam( sceneId, selfId, itemidx1, 1, 1) >= x809262_g_qianghuaLevelT[qianhuLevel][2] then
	--强化
	ret,arg0 = LuaFnEquipEnhance( sceneId, selfId, itemidx1, itemidx2 )
	end

	if ret == 0 then
		if arg0 >= 2 then
			local	szTranItm1	= GetBagItemTransfer( sceneId, selfId, itemidx1 )
			local	szTranItm2	= GetBagItemTransfer( sceneId, selfId, itemidx2 )
			local	szMsg				= format( "#W#{_INFOUSR%s}#{EQ_1}#{_INFOMSG%s}#{EQ_2}%d#{EQ_3}#{_INFOMSG%s}#{EQ_4}",
														LuaFnGetName( sceneId, selfId ), szTranItm2, arg0, szTranItm1 )
			--公告精简，小于5级的强化，不发公告
			if (arg0 >= 90) then
				AddGlobalCountNews( sceneId, szMsg )
			end
		end
		
		gem_index = LuaFnGetItemTableIndexByIndex( sceneId, selfId, itemidx2 )
		
		if x809262_g_QianghualuId == gem_index then
			local r, t = LuaFnEraseItemTimes( sceneId, selfId, itemidx2, x809262_g_QianghualuTime )
			--PrintNum(r);
			--PrintNum(t)
			BeginEvent(sceneId)
			--local str = "天罡强化露剩余使用次数%d"
			local	szMsg				= format( "天罡强化露剩余使用次数%d/%d",
														tonumber(t), tonumber(x809262_g_QianghualuTime) );
			AddText(sceneId,szMsg);
			EndEvent(sceneId)
			DispatchMissionTips(sceneId,selfId)
		elseif gem_index == x809262_g_QianghualuId1 then
		LuaFnDelAvailableItem(sceneId,selfId,x809262_g_QianghualuId1,1)	
		else
			LuaFnEraseItem( sceneId, selfId, itemidx2 )
		end
		LuaFnSendSpecificImpactToUnit(sceneId, selfId, selfId, selfId, 49, 0);
	end

	if ret == -1 then
		text="未知错误。"
	end
	
	if ret == -2 then
		text="装备不可用。"
	end
	
	if ret == -3 then
		text="强化精华不可用。"
	end
	
	if ret == -4 then
		text="该装备的强化等级已经最大。"
	end

	if ret == -5 then
		text="强化该装备需要#{_EXCHG%d}，您身上的现金不足。" --zchw
		text=format( text, arg0 )
	end

	if ret == -6 then
		text="好可惜啊您的装备强化失败了,别灰心!!!"
		
		if x809262_g_QianghualuId == gem_index  then
			local r, t = LuaFnEraseItemTimes( sceneId, selfId, itemidx2, x809262_g_QianghualuTime )
			--PrintNum(r);
			--PrintNum(t)
			BeginEvent(sceneId)
			local	szMsg				= format( "天罡强化露剩余使用次数%d/%d",
														tonumber(t), tonumber(x809262_g_QianghualuTime) );
			AddText(sceneId,szMsg);
			EndEvent(sceneId)
			DispatchMissionTips(sceneId,selfId)
		elseif gem_index == x809262_g_QianghualuId1 then
		LuaFnDelAvailableItem(sceneId,selfId,x809262_g_QianghualuId1,1)	
		LuaFnCostMoneyWithPriority( sceneId, selfId,  300 );
		else
			LuaFnEraseItem( sceneId, selfId, itemidx2 )
		end
		--LuaFnEraseItem( sceneId, selfId, itemidx2 )
		SetBagItemParam( sceneId, selfId, itemidx1, 1, 1,GetBagItemParam( sceneId, selfId, itemidx1, 1, 1)+1)
		   BeginUICommand(sceneId)
		   UICommand_AddInt(sceneId,2014);
		   UICommand_AddInt(sceneId,GetBagItemParam( sceneId, selfId, itemidx1, 1, 1));
		   EndUICommand(sceneId )
		   DispatchUICommand(sceneId,selfId, 1002  )
		   	
	end
	
	if ret >= 0 then
	SetBagItemParam( sceneId, selfId, itemidx1, 3, 1,arg0)
