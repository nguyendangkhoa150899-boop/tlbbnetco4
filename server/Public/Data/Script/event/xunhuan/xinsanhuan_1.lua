function x050220_CheckAccept( sceneId, selfId )
	-- ÒÑ¾­½Ó¹ýÔò²»·ûºÏÌõ¼þ
	if IsHaveMission( sceneId, selfId, x050220_g_MissionId ) > 0 then
		return 0
	end
	
	-- ²»ÄÜÓÐÆäËûµÄÈÎÎñ
