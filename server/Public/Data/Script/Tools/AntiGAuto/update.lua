--**********************************--
--*         Create Question        *--
--**********************************--
function x950100_CreateQuestion(sceneId,selfId)

	--*********************--
	local x=tostring(random(9999))
	--*********************--
	while strlen(x)<4 do
		x="0"..x
	end
	--*********************--
	BeginUICommand(sceneId)
		UICommand_AddString(sceneId,x950100_g_Image_List[strsub(x,1,1)][random(getn(x950100_g_Image_List[strsub(x,1,1)]))])
		UICommand_AddString(sceneId,x950100_g_Image_List[strsub(x,2,2)][random(getn(x950100_g_Image_List[strsub(x,2,2)]))])
		UICommand_AddString(sceneId,x950100_g_Image_List[strsub(x,3,3)][random(getn(x950100_g_Image_List[strsub(x,3,3)]))])
		UICommand_AddString(sceneId,x950100_g_Image_List[strsub(x,4,4)][random(getn(x950100_g_Image_List[strsub(x,4,4)]))])
	EndUICommand(sceneId)
	DispatchUICommand(sceneId,selfId,170120160)
	--*********************--
	SetMissionData(sceneId,selfId,MD_ANTI_GAUTO_CODE,tonumber(x))
	--*********************--

end
--**********************************--
--*          Update Answer         *--
--**********************************--
function x950100_UpdateAnswer(sceneId,selfId,Answer)

	--*********************--
	local Solution=GetMissionData(sceneId,selfId,MD_ANTI_GAUTO_CODE)
	--*********************--
	if Answer~=Solution then
		BeginEvent(sceneId)
			AddText(sceneId,"Th§t ğáng tiªc, câu trä l¶i cüa các hÕ không ğúng.")
		EndEvent(sceneId)
		DispatchMissionTips(sceneId,selfId)
		
		LuaFnCancelSpecificImpact(sceneId,selfId,32001)											--Hüy bö impact vào tù
		
		BeginUICommand(sceneId)
		EndUICommand(sceneId)
		DispatchUICommand(sceneId,selfId,170120161)
		
		x950100_GotoPrison(sceneId,selfId)
	else
		BeginEvent(sceneId)
			AddText(sceneId,"Chúc m×ng các hÕ ğã ğáp ğúng câu höi l¥n này.")
		EndEvent(sceneId)
		DispatchMissionTips(sceneId,selfId)
		
		LuaFnCancelSpecificImpact(sceneId,selfId,32001)											--Hüy bö impact vào tù
		
		BeginUICommand(sceneId)
		EndUICommand(sceneId)
		DispatchUICommand(sceneId,selfId,170120161)
	end
	--*********************--
	SetMissionData(sceneId,selfId,MD_ANTI_GAUTO_CODE,-1)
	--*********************--

end
