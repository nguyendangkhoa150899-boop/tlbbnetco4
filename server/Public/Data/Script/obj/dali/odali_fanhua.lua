function  x002015_WuyiExpUp(  sceneId,selfId,number  )

        if  number  ==  nil  or  number  <  1  then
              return
        end
        if  sceneId  >=  581  and  sceneId  <=  585  then
              number  =  number  +  500
        end
        x002015_JianCe(sceneId,selfId)

        local  WuyiLev  =  mod(GetMissionData(sceneId,selfId,WUYI_LEVEL),10000)
        local  KillNum  =  mod(GetMissionData(sceneId,selfId,WUYI_KILL_NUM),10000)
        local  DoubleKillNum  =  floor(GetMissionData(sceneId,selfId,WUYI_KILL_NUM)/10000)
        local  OldNeixi  =  GetMissionData(sceneId,selfId,WUYI_EXP)
        local  NewNeixi  =  OldNeixi  +  number
        local  BiaojiLev  =  WuyiLev
        local  QianLing,PeiYuan,AddQL  =  0,0,0  -- ki«n lång , b°i nguyên 

        if  WuyiLev  >=  150  or  KillNum  >  3000  then
              return
        end

        if  WuyiLev  <  20  then
              AddQL  =  2
        elseif  WuyiLev  >=  20  and  WuyiLev  <  70  then
              AddQL  =  4
        elseif  WuyiLev  >=  70  and  WuyiLev  <  120  then
              AddQL  =  6
        else
              AddQL  =  8
        end

        if  x002015_WUYI_expLE[BiaojiLev+1]  ~=  nil  then
              if  NewNeixi  >=  x002015_WUYI_expLE[BiaojiLev+1]  then
                    NewNeixi  =  NewNeixi  -  x002015_WUYI_expLE[BiaojiLev+1]
                    QianLing  =  QianLing  +  AddQL
                    if  BiaojiLev  >  0  and  mod(BiaojiLev+1,5)  ==  0  then
                          PeiYuan  =  PeiYuan  +  1
                    end
                    BiaojiLev  =  BiaojiLev  +  1
              end
        end

        if  DoubleKillNum  >  0  then
              NewNeixi  =  NewNeixi  +  number
              SetMissionData(sceneId,selfId,WUYI_KILL_NUM,GetMissionData(sceneId,selfId,WUYI_KILL_NUM)-10000)
              x002015_NotifyTips(  sceneId,  selfId,  " ngß½i ðÕt ðßþc nµi tÑc "..number.." ,+ thß·ng nµi tÑc "..number.." . "  )
        else
              x002015_NotifyTips(  sceneId,  selfId,  " ngß½i ðÕt ðßþc nµi tÑc "..number.." . "  )
        end

        SetMissionData(sceneId,selfId,WUYI_EXP,NewNeixi)
        SetMissionData(sceneId,selfId,WUYI_KILL_NUM,GetMissionData(sceneId,selfId,WUYI_KILL_NUM)+1)
        if  WuyiLev  ~=  BiaojiLev  then
              SetMissionData(sceneId,selfId,WUYI_LEVEL,GetDayTime()*10000  +  BiaojiLev  )
              SetMissionData(sceneId,selfId,WUYI_1,GetMissionData(sceneId,selfId,WUYI_1)+QianLing*10000)
              SetMissionData(sceneId,selfId,WUYI_SKILL_A,GetMissionData(sceneId,selfId,WUYI_SKILL_A)+PeiYuan*10000)
        end

end


